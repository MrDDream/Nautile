function save(key, value) { try { localStorage.setItem(key, value); } catch (e) {} }

function setLang(lang, remember) {
  const dict = lang === "fr" ? FR : EN;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => { const v = dict[el.dataset.i18n]; if (v != null) el.textContent = v; });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { const v = dict[el.dataset.i18nHtml]; if (v != null) el.innerHTML = v; });
  document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  document.title = META[lang].title;
  document.querySelector('meta[name="description"]').content = META[lang].desc;
  if (remember) save("nautile-lang", lang);
  updateShots();
  applyRelease();
}

function setTheme(theme, remember) {
  document.documentElement.dataset.theme = theme;
  document.querySelectorAll("[data-theme-set]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.themeSet === theme)));
  document.querySelector('meta[name="theme-color"]').content = theme === "light" ? "#F6F4EF" : "#0B0E12";
  if (remember) save("nautile-theme", theme);
  updateShots();
}

/** The screenshots exist per language and theme: shots/<lang>-<theme>-<screen>.png, desktop/<lang>-<theme>-<screen>.webp */
function updateShots() {
  const lang = document.documentElement.lang === "fr" ? "fr" : "en";
  const theme = document.documentElement.dataset.theme === "light" ? "light" : "dark";
  document.querySelectorAll("[data-shot]").forEach((img) => { img.src = `assets/shots/${lang}-${theme}-${img.dataset.shot}.png`; });
  document.querySelectorAll("[data-desk]").forEach((img) => { img.src = `assets/desktop/${lang}-${theme}-${img.dataset.desk}.webp`; });
}

/** A group of tabs: [attr] on the buttons, [attr]-pane on what each shows. */
function tabs(attr, pick) {
  const buttons = document.querySelectorAll(`[data-${attr}]`);
  const show = (v) => {
    buttons.forEach((b) => b.setAttribute("aria-pressed", String(b.dataset[attr.replace(/-./g, (m) => m[1].toUpperCase())] === v)));
    document.querySelectorAll(`[data-${attr}-pane]`).forEach((p) => { p.hidden = p.getAttribute(`data-${attr}-pane`) !== v; });
  };
  buttons.forEach((b) => b.addEventListener("click", () => show(b.getAttribute(`data-${attr}`))));
  if (pick) show(pick);
  return show;
}

