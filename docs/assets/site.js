/*
 * The download links: they point to the releases page, then to the files of the latest release once GitHub said
 * which they are (one request per visit, kept for an hour; GitHub allows 60 an hour per address). If the request
 * fails, the links stay on the releases page.
 */
const ASSETS = {
  "apk-arm64": /^Nautile-v[\d.]+-arm64-v8a\.apk$/,
  "apk-v7": /^Nautile-v[\d.]+-armeabi-v7a\.apk$/,
  "apk-universal": /^Nautile-v[\d.]+\.apk$/,
  "win-setup": /-setup\.exe$/,
  "win-portable": /-portable\.zip$/,
  "deb": /_amd64\.deb$/,
  "rpm": /\.x86_64\.rpm$/,
  "tar": /-linux-x86_64\.tar\.gz$/,
  "dmg": /-macos-arm64\.dmg$/,
};
const CACHE = "nautile-release";
let release = null;

function applyRelease() {
  if (!release) return;
  document.querySelectorAll("[data-asset]").forEach((a) => { const url = release.assets[a.dataset.asset]; if (url) a.href = url; });
  if (release.tag) document.querySelectorAll("[data-version]").forEach((el) => { el.textContent = release.tag; });
}

function useRelease(json) {
  const assets = {};
  for (const a of json.assets || []) {
    for (const [key, re] of Object.entries(ASSETS)) {
      if (!assets[key] && re.test(a.name) && /^https:\/\/github\.com\//.test(a.browser_download_url)) assets[key] = a.browser_download_url;
    }
  }
  const tag = /^v\d+\.\d+\.\d+$/.test(json.tag_name || "") ? json.tag_name : null;
  return { tag, assets };
}

(async function loadRelease() {
  try {
    const kept = JSON.parse(sessionStorage.getItem(CACHE) || "null");
    if (kept && Date.now() - kept.at < 3600e3) { release = kept.release; applyRelease(); return; }
  } catch (e) {}
  try {
    const r = await fetch("https://api.github.com/repos/MrDDream/Nautile/releases/latest", { headers: { Accept: "application/vnd.github+json" } });
    if (!r.ok) return;
    release = useRelease(await r.json());
    applyRelease();
    try { sessionStorage.setItem(CACHE, JSON.stringify({ at: Date.now(), release })); } catch (e) {}
  } catch (e) {
    // Offline, blocked or over GitHub's limit: the releases page stays.
  }
})();

