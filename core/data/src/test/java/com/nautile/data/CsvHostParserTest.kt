package com.nautile.data

import com.nautile.data.importer.CsvHostParser
import com.nautile.data.importer.HostImport
import org.junit.Assert.assertEquals
import org.junit.Test

class CsvHostParserTest {
    @Test fun parsesHeaderInAnyOrderWithQuotes() {
        val csv = "Host,Label,Port,User,Group,Tags\r\n" +
            "192.168.1.10,nas-unraid,,root,Homelab,\"nas;storage\"\r\n" +
            "\n" +
            "vps.example.org,\"vps, \"\"ovh\"\"\",2222,debian,VPS,prod|web\n" +
            ",empty-host,22,x,,\n"
        val hosts = CsvHostParser.parse(csv)
        assertEquals(2, hosts.size)
        hosts[0].let {
            assertEquals("nas-unraid", it.alias)
            assertEquals(22, it.port)
            assertEquals("Homelab", it.group)
            assertEquals(listOf("nas", "storage"), it.tags)
        }
        hosts[1].let {
            assertEquals("vps, \"ovh\"", it.alias)
            assertEquals(2222, it.port)
            assertEquals(listOf("prod", "web"), it.tags)
        }
    }

    @Test fun byteOrderMarkAndSemicolonsFromExcel() {
        val hosts = HostImport.parse("\uFEFFhostname;alias;port;tags\r\n10.0.0.1;nas;99999;\"a;b\"\r\n10.0.0.2;pi;2222;\r\n")
        assertEquals(listOf("nas", "pi"), hosts.map { it.alias })
        assertEquals(22, hosts[0].port) // out of range
        assertEquals(listOf("a", "b"), hosts[0].tags)
        assertEquals(2222, hosts[1].port)
        assertEquals("pi", CsvHostParser.parse("\uFEFFhostname,alias\n1.2.3.4,pi").single().alias)
    }

    @Test fun tellsCsvFromSshConfig() {
        assertEquals("a", HostImport.parse("alias,hostname\na,1.2.3.4").single().alias)
        assertEquals("b", HostImport.parse("\uFEFFHost b\n  HostName 1.2.3.4").single().alias)
        assertEquals("1.2.3.4", HostImport.parse("\uFEFFHost b\n  HostName 1.2.3.4").single().hostname)
        // A comment that looks like a CSV header is still a comment of an OpenSSH config.
        val config = "# host list; generated by ansible, address book\n\nHost web\n  HostName 10.0.0.1\n"
        assertEquals(false, HostImport.looksCsv(config))
        assertEquals("10.0.0.1", HostImport.parse(config).single().hostname)
    }

    @Test fun aliasDefaultsToHostname() {
        val hosts = CsvHostParser.parse("hostname\npi.lan")
        assertEquals("pi.lan", hosts.single().alias)
    }
}
