#!/usr/bin/env python3
"""Regenerates core/i18n/.../EnStrings.kt from core/i18n/translations/*.tsv (French<TAB>English, Kotlin escapes)."""
import glob, os
root = os.path.join(os.path.dirname(__file__), '..')
pairs = {}
for f in sorted(glob.glob(os.path.join(root, 'core/i18n/translations/*.tsv'))):
    for line in open(f, encoding='utf-8').read().split('\n'):
        if line.strip():
            fr, en = line.split('\t', 1)
            pairs[fr] = en
kt = lambda s: '"' + s.replace('"', '\\"') + '"'
body = '\n'.join('        %s to %s,' % (kt(k), kt(v)) for k, v in sorted(pairs.items()))
out = os.path.join(root, 'core/i18n/src/main/kotlin/com/nautile/i18n/EnStrings.kt')
open(out, 'w', encoding='utf-8').write(
    'package com.nautile.i18n\n\n/** English text for every French source string (generated by scripts/gen-strings.py). */\n'
    'internal object EnStrings {\n    val map: Map<String, String> = hashMapOf(\n' + body + '\n    )\n}\n')
print(len(pairs), 'strings')
