#!/usr/bin/env python3
"""Regenerates core/i18n/.../EnStrings.kt from core/i18n/translations/*.tsv (French<TAB>English, Kotlin escapes)."""
import glob
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'core/i18n/src/main/kotlin/com/nautile/i18n/EnStrings.kt')


def unescaped_dollar(s):
    """Index of the first `$` not escaped as `\\$` (it would start a Kotlin string template), or -1."""
    i = 0
    while i < len(s):
        if s[i] == '\\':
            i += 2
            continue
        if s[i] == '$':
            return i
        i += 1
    return -1


def kotlin_string(s):
    return '"' + s.replace('"', '\\"') + '"'


def read_pairs():
    pairs = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'core/i18n/translations/*.tsv'))):
        with open(path, encoding='utf-8') as f:
            for number, line in enumerate(f.read().split('\n'), 1):
                if not line.strip():
                    continue
                if '\t' not in line:
                    sys.exit('%s:%d: no tab between the French and the English text' % (os.path.relpath(path, ROOT), number))
                french, english = line.split('\t', 1)
                for text in (french, english):
                    col = unescaped_dollar(text)
                    if col >= 0:
                        sys.exit('%s:%d: `$` must be written `\\$` (Kotlin string template): %s'
                                 % (os.path.relpath(path, ROOT), number, text))
                pairs[french] = english
    return pairs


def main():
    pairs = read_pairs()
    body = '\n'.join('        %s to %s,' % (kotlin_string(k), kotlin_string(v)) for k, v in sorted(pairs.items()))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(
            'package com.nautile.i18n\n\n/** English text for every French source string (generated by scripts/gen-strings.py). */\n'
            'internal object EnStrings {\n    val map: Map<String, String> = hashMapOf(\n' + body + '\n    )\n}\n')
    print(len(pairs), 'strings')


if __name__ == '__main__':
    main()
